/** Возвращает готовый <svg>-элемент. Контур наследует цвет текста (stroke: currentColor). */
function Icon(name, size = 20) {
  const host = document.createElement('span');
  host.innerHTML = `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" ` +
    `stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${ICONS[name] || ''}</svg>`;
  return host.firstElementChild;
}

/** Заполняет все элементы [data-icon="имя"] (используется для статичных кнопок в index.html). */
function mountIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (!el.querySelector('svg')) el.prepend(Icon(el.dataset.icon, +el.dataset.iconSize || 20));
  });
}
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => mountIcons());
else mountIcons();
